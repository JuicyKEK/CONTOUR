namespace Game.Scripts.Instructions.Interfaces
{
    /// <summary>
    /// Сохранение/загрузка списка полученных игроком кассет (JSON-файл с Id кассет).
    /// Регистрируется как глобальный бин JuicyDI - систему чекпоинтов можно подключить через [Inject].
    /// </summary>
    public interface IAudioTapeSaveService
    {
        /// <summary>
        /// Есть ли файл сохранения кассет.
        /// </summary>
        bool HasSave { get; }

        /// <summary>
        /// Сохраняет Id всех полученных кассет в JSON-файл. Вызывается на чекпоинтах.
        /// </summary>
        void Save();

        /// <summary>
        /// Загружает сохранение и восстанавливает в реестре, какие кассеты уже были получены.
        /// Возвращает false, если сохранения нет или его не удалось прочитать (реестр тогда не меняется).
        /// </summary>
        bool Load();

        /// <summary>
        /// Удаляет файл сохранения кассет (например, при старте новой игры).
        /// </summary>
        void DeleteSave();
    }
}
