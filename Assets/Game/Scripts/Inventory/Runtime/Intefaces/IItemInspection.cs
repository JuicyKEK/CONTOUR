using System;
using UnityEngine;

namespace Game.Scripts.Inventory
{
    /// <summary>
    /// Осмотр предмета при первом подборе (по примеру Resident Evil): предмет подлетает к камере, всё за ним
    /// размывается, снизу - название предмета. Игрок крутит предмет, зажав ЛКМ; по Esc или кнопке "Принять"
    /// предмет уменьшается, летит к панели инвентаря и только тогда появляется в инвентаре.
    /// Предметы с ключом, который уже осматривали, сразу идут в инвентарь - осмотр не начинается.
    /// </summary>
    public interface IItemInspection
    {
        /// <summary>
        /// Идёт осмотр (предмет летит к камере, осматривается или летит в инвентарь).
        /// </summary>
        bool IsInspecting { get; }

        /// <summary>
        /// Начинает осмотр, если предмет с таким ключом ещё не осматривали.
        /// </summary>
        /// <param name="item">Предмет инвентаря (ключ, иконка).</param>
        /// <param name="displayName">Название предмета - подпись под ним.</param>
        /// <param name="source">Объект на сцене: с него снимается внешний вид (меши и материалы).
        /// Сам объект вызывающий прячет сразу после начала осмотра.</param>
        /// <param name="onFinished">Вызывается, когда предмет долетел до инвентаря, - в этот момент его кладут в инвентарь.</param>
        /// <returns>false - осмотра не будет (этот предмет уже осматривали, идёт другой осмотр, курсор занят
        /// открытой панелью, у предмета нет видимых мешей): предмет надо сразу положить в инвентарь.</returns>
        bool TryInspect(IInventoryObject item, string displayName, GameObject source, Action onFinished);
    }
}
