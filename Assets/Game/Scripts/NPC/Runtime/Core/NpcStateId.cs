namespace Game.Scripts.NPC.Runtime.Core
{
    /// <summary>
    /// Идентификаторы состояний FSM бота. Сюжет и триггеры переключают состояния
    /// именно по этому enum (через публичные no-op методы NpcController -
    /// см. NpcController.ForceIdle()/ForcePatrol()/... для привязки из UnityEvent)
    /// или шагами графа бота ("NPC/Set State").
    /// Числа не менять - они сохранены в сценах (стартовое состояние ботов).
    /// </summary>
    public enum NpcStateId
    {
        /// <summary>Стоит на месте, сам никуда не переходит - ждёт команды сюжета.</summary>
        Idle = 0,

        /// <summary>Стоит и следит взглядом за игроком; агрессивный при виде игрока начинает погоню.</summary>
        Observe = 1,

        /// <summary>Спокойное поведение: обход маршрута (у мимика - изображение своей роли на точках маршрута).</summary>
        Patrol = 2,

        /// <summary>Погоня за игроком (или сюжетная погоня, когда бот всегда знает, где игрок).</summary>
        Chase = 3,

        Panic = 4,

        /// <summary>
        /// Случайное блуждание по окрестностям без цели. Сам бот сюда больше не попадает
        /// (у запертой двери он теперь ищет игрока - <see cref="Search"/>), состояние оставлено для сюжета.
        /// </summary>
        Wander = 5,

        /// <summary>
        /// Поиск потерянного игрока: сначала вокруг места, где бот видел его последним, а при высоком
        /// заражении зоны - потом по всей зоне. Не нашёл - возвращается к спокойному поведению.
        /// </summary>
        Search = 6,

        /// <summary>Атака: удар (игрок жив) или убийство - см. NpcTypeDefinitionSO.AttackKind.</summary>
        Attack = 7,

        /// <summary>Действие на месте по ключу анимации/звука (превращение, злость, "отдаёт посылку").</summary>
        Perform = 8,

        /// <summary>Идёт в заданную точку (команда графа бота) и там останавливается.</summary>
        MoveTo = 9
    }
}
