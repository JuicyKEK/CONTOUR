namespace Game.Scripts.LocationScene.Runtime.Interfaces
{
    /// <summary>
    /// Чекпоинт игрока: на какой локации и в какой точке он появится при загрузке сохранения или
    /// после смерти. Чекпоинт назначает сюжет (действие графа "Save/Set Player Checkpoint"); когда игрок
    /// переходит в другую локацию, чекпоинтом становится её чекпоинт по умолчанию. В файл чекпоинт
    /// попадает при общем сохранении игры (IGameSaveService.SaveGame, действие "Save/Save Game").
    /// </summary>
    public interface IPlayerCheckpointService
    {
        /// <summary>
        /// Ключ локации назначенного чекпоинта (null - чекпоинт ещё не назначался).
        /// </summary>
        string CheckpointLocationId { get; }

        /// <summary>
        /// Ключ назначенного чекпоинта.
        /// </summary>
        string CheckpointId { get; }

        /// <summary>
        /// Назначает чекпоинт игрока - в том числе на локации, которая сейчас не загружена. Локация
        /// чекпоинта: если его сцена загружена - та, в сцене которой он стоит (для чекпоинта в переходной
        /// сцене - текущая локация игрока); если нет - та, в списке чекпоинтов которой есть этот ключ.
        /// В файл чекпоинт попадает при следующем сохранении игры. Возвращает false, если чекпоинта с
        /// таким ключом нет.
        /// </summary>
        bool SetCheckpoint(string checkpointId);

        /// <summary>
        /// Возвращает игру к последнему сохранению (например, при смерти игрока): игра перезапускается
        /// с сохранённой локации и чекпоинта, все механики заново читают свои сохранения.
        /// </summary>
        void ReturnToLastSave();
    }
}
