namespace Game.Scripts.LocationState.Runtime.Interfaces
{
    /// <summary>
    /// Хранилище состояний объектов локаций. Живёт в сцене ядра всю игру:
    ///  - сцена загрузилась - каждый объект регистрируется и сразу получает своё сохранённое состояние;
    ///  - сцена выгружается - состояния её объектов запоминаются до следующей загрузки;
    ///  - сохранение игры - состояния всех объектов пишутся в файл, загрузка игры - читаются из него.
    /// </summary>
    public interface ILocationStateService
    {
        /// <summary>
        /// Объект появился на загруженной сцене. Если для него есть сохранённое состояние, объект сразу его получает.
        /// </summary>
        void Register(ILocationStateObject stateObject);

        /// <summary>
        /// Объект удаляется со сцены раньше, чем выгружается сцена (например, подобранный предмет), -
        /// его состояние больше не запрашивается. То, что уже запомнено, остаётся.
        /// </summary>
        void Unregister(ILocationStateObject stateObject);

        /// <summary>
        /// Запомнить состояние объекта прямо сейчас (например, в момент подбора - потом объекта уже не будет).
        /// </summary>
        void StoreState(ILocationStateObject stateObject);
    }
}
